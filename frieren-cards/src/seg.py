def build(ep):
    e = EPISODES[ep]
    anchors, groups = e['anchors'], e['groups']
    assert len(anchors) == len(groups) + 1, f'ep{ep}: anchors={len(anchors)} groups={len(groups)}'
    segs = []
    cid = 1
    for i, texts in enumerate(groups):
        s0, s1 = anchors[i], anchors[i + 1]
        total = sum(len(t) for t in texts) or 1
        t = s0
        for j, text in enumerate(texts):
            dur = (s1 - s0) * len(text) / total
            st = t
            en = s1 if j == len(texts) - 1 else t + dur
            segs.append({'id': cid, 's': round(st, 2), 'e': round(en, 2), 'ja': text})
            t = en
            cid += 1
    out_dir = os.path.join(S, f'ep{ep}')
    os.makedirs(out_dir, exist_ok=True)
    json.dump(segs, open(os.path.join(out_dir, 'segs.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return segs


